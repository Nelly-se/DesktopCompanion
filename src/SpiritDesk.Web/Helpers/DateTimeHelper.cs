// =============================================================================
// DateTimeHelper.cs — 按本地小时返回问候语（纯函数，无状态）
// =============================================================================
// 数据结构：输入 DateTime，输出 string；无集合
// C# 语法：
//   - static class + static method：工具类，不实例化
//   - switch 表达式：根据 Hour 匹配，&lt; 6 / &lt; 12 等为模式，_ 为默认分支
// =============================================================================

namespace SpiritDesk.Web.Helpers;

/// <summary>
/// 时间文案辅助类。
/// 作用：把当前时间转换成首页、聊天页等位置可以直接展示的中文问候语。
/// 这个类不访问数据库、不依赖配置，只根据传入的 DateTime 计算结果，所以属于简单的纯工具类。
/// </summary>
public static class DateTimeHelper
{
    /// <summary>
    /// 根据小时段返回问候文案。
    /// 规则：0-5 点提示夜深了，6-11 点早上好，12-17 点下午好，18-23 点晚上好。
    /// </summary>
    public static string GetGreetingByHour(DateTime now)
    {
        // switch 表达式按从上到下的顺序匹配，第一个满足条件的分支就是返回值。
        return now.Hour switch
        {
            < 6 => "夜深了",
            < 12 => "早上好",
            < 18 => "下午好",
            _ => "晚上好"
        };
    }
}
